export function getChapterBySlug(slug: string): Chapter | undefined {
  if (!slug) return chapters[0]
  return chapters.find((c) => c.slug === slug)
}

export function getAllSlugs(): string[] {
  return chapters.map((c) => c.slug).filter(Boolean)
}
